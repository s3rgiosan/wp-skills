def check_php_tags(target, namespace):
    """Fail the build when a generated PHP file holds a PHP tag the generator did not write.

    Every file opens with one literal `<?php` line. The only other tag the generator writes is the screenshot
    echo in views/guide.php, matched exactly (fixed namespace, screenshot id from [a-z0-9_-]) and removed before the
    scan, as is the single `?>` that closes the file's header. Whatever `<?` or `?>` is left is guide- or
    CLI-derived and fails the build.
    """
    echo_re = re.compile(re.escape(shot_echo(namespace, "@@ID@@")).replace("@@ID@@", SHOT_ID_RE))
    problems = []
    for root, _, files in os.walk(target):
        for name in files:
            if not name.endswith(".php"):
                continue
            path = os.path.join(root, name)
            with open(path, encoding="utf-8") as handle:
                text = handle.read()
            if not text.startswith("<?php\n"):
                problems.append(f"{path}: does not start with the generator's <?php line")
                continue
            body = text[len("<?php\n"):]
            if os.path.relpath(path, target) == os.path.join("views", "guide.php"):
                body = echo_re.sub("", body)
                head, sep, rest = body.partition("\n?>\n")
                if not sep:
                    problems.append(f"{path}: the header's closing ?> is missing")
                    continue
                body = head + rest
            if "<?" in body or "?>" in body:
                problems.append(f"{path}: contains a PHP tag the generator did not write")
    if problems:
        fail_build(target, "stray PHP tag check failed:\n" + "\n".join(problems))


def lint(target):
    php = shutil.which("php")
    if not php:
        warn("php is not on PATH: generated PHP was not syntax-checked")
        return
    failed = []
    for root, _, files in os.walk(target):
        for name in files:
            if name.endswith(".php"):
                path = os.path.join(root, name)
                result = subprocess.run([php, "-l", path], capture_output=True, text=True)
                if result.returncode != 0:
                    failed.append(f"{path}: {clean(result.stdout + result.stderr)}")
    if failed:
        fail_build(target, "php -l failed:\n" + "\n".join(failed))


