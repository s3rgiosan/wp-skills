"""to-plugin.py — build a WordPress plugin that shows a user guide inside wp-admin.

Reads the guide page written to the HTML output contract (see references/outputs.md), its shots/ folder and an
optional sections.json, and writes a plugin folder:

  <slug>/<slug>.php                main file (header, loader)
  <slug>/includes/class-guide.php  menu page, dashboard widget, Help tabs, editor panel, screenshot endpoint
  <slug>/includes/data.php         section index, screenshot list, screen-to-section links
  <slug>/views/guide.php           the guide as admin markup
  <slug>/views/shots/<id>.php      one screenshot per file, base64 behind an ABSPATH guard
  <slug>/assets/                   stylesheet, index and checklist script, block editor panel script
  <slug>/languages/<slug>.pot      translatable strings of the plugin (no guide content)
  <slug>/.wp-user-guide-build    build marker holding the slug

The guide and its screenshots are reachable only through wp-admin by users with the guide capability: every PHP
file exits on a direct request, and screenshots are served by an admin-post handler that checks the capability.
assets/ holds the stylesheet and scripts as static public files; they carry no guide content.

--force replaces an existing <out>/<slug>/ only when it holds a build marker file (.wp-user-guide-build,
.wp-admin-guide-build or .wp-editor-guide-build) containing the slug, or, when no marker file exists, when both
<slug>.php and includes/class-guide.php carry one of the generator marks ("Generated by the wp-user-guide skill",
"Generated by the wp-admin-guide skill" or "Generated by the wp-editor-guide skill"). The build happens in a
temporary folder beside the target and is swapped in after the checks pass.

The plugin's own interface is English and translatable (text domain = the slug, Domain Path /languages): menu,
page and widget label, Help tab, editor panel title, error text, Plugin Name and Description. The POT comes from
`wp i18n make-pot` when wp is on the PATH, otherwise from this script's own string table. The guide's text, section
titles and h1 are content and stay in the guide's language. --name sets the Plugin Name; write it in English, since
it is translatable.

Usage:
  python3 to-plugin.py guide.html --slug acme-user-guide --out build/
  python3 to-plugin.py guide.html --slug acme-user-guide --out build/ --sections sections.json \
      --name "User Guide" --capability edit_posts --version 1.0.0 --force
  python3 to-plugin.py --help

sections.json maps admin screens to guide section ids (each id must be a section of the page):
  {
    "post_types": { "post": "posts", "page": "pages", "acme_event": "events" },
    "taxonomies": { "category": "categories", "acme_topic": "categories" },
    "screens":    { "nav-menus": "menus", "upload": "media" }
  }

Requires Beautiful Soup 4: pip install beautifulsoup4
"""
