def new_shot_token():
    """Choose a random placeholder token for this build."""
    global SHOT_TOKEN, SHOT_TOKEN_RE
    marker = secrets.token_hex(12)
    SHOT_TOKEN = "@@SHOT-" + marker + ":{}@@"
    SHOT_TOKEN_RE = re.compile("@@SHOT-" + marker + ":(" + SHOT_ID_RE + ")@@")


def clean(text):
    """Collapse whitespace; control characters count as whitespace."""
    return re.sub(r"\s+", " ", re.sub(r"[\x00-\x1f\x7f]", " ", text)).strip()


def reject_php_tags(label, text):
    """Exit 2 when text holds a PHP open or close tag."""
    if "<?" in text or "?>" in text:
        fail(f"{label} contains a PHP tag (<? or ?>): {text[:60]!r}")


def php_string(value):
    """A single-quoted PHP string literal."""
    return "'" + str(value).replace("\\", "\\\\").replace("'", "\\'") + "'"


def php_array(value, indent=1):
    """A long-array PHP literal for nested dicts, lists and strings."""
    pad = "\t" * indent
    end = "\t" * (indent - 1)
    if isinstance(value, dict):
        if not value:
            return "array()"
        # WordPress-Core aligns double arrows up to column 60 (tabs count as 4 columns); a longer key
        # takes a single space before its arrow.
        keys = [php_string(k) for k in value]
        fits = [len(k) for k in keys if indent * 4 + len(k) + 2 <= 60]
        width = max(fits) if fits else 0
        rows = [
            f"{pad}{k.ljust(width) if len(k) <= width else k} => {php_array(v, indent + 1)},"
            for k, v in zip(keys, value.values())
        ]
        return "array(\n" + "\n".join(rows) + f"\n{end})"
    if isinstance(value, list):
        if not value:
            return "array()"
        return "array(\n" + "\n".join(f"{pad}{php_array(v, indent + 1)}," for v in value) + f"\n{end})"
    return php_string(value)


def header_text(text):
    """Single-line text that cannot close a PHP docblock or open or close a PHP tag."""
    while True:
        stripped = text.replace("*/", "").replace("<?", "").replace("?>", "")
        if stripped == text:
            return clean(text)
        text = stripped


def truncate(text, limit):
    """Shorten text to at most limit characters on a word boundary, ending in an ellipsis."""
    if len(text) <= limit:
        return text
    cut = text[: limit - 1]
    space = cut.rfind(" ")
    if space > limit // 2:
        cut = cut[:space]
    return cut.rstrip(" .,;:") + "\u2026"


def studly(slug):
    return "".join(part.capitalize() for part in slug.split("-"))


def camel(slug):
    name = studly(slug)
    return name[:1].lower() + name[1:]


def shot_id(path):
    """Screenshot id from its file name, reduced to what sanitize_key() keeps."""
    stem = os.path.splitext(os.path.basename(path))[0].lower()
    return re.sub(r"[^a-z0-9_-]", "-", stem)


def check_shot_file(name, path):
    """Exit 2 unless path is a regular, non-symlink PNG file of at most MAX_SHOT_BYTES."""
    try:
        info = os.lstat(path)
        with open(path, "rb") as handle:
            signature = handle.read(len(PNG_SIGNATURE))
    except OSError as error:
        fail(f"cannot read screenshot {name!r}: {error}")
    if stat.S_ISLNK(info.st_mode):
        fail(f"screenshot {name!r} is a symlink: copy the file into the shots folder")
    if not stat.S_ISREG(info.st_mode):
        fail(f"screenshot {name!r} is not a regular file")
    if info.st_size > MAX_SHOT_BYTES:
        fail(f"screenshot {name!r} is {info.st_size} bytes, over the {MAX_SHOT_BYTES} byte (5 MB) limit")
    if signature != PNG_SIGNATURE:
        fail(f"screenshot {name!r} is not a PNG image (the file does not start with the PNG signature)")


def load_shots(shots_dir):
    shots = {}
    if not os.path.isdir(shots_dir):
        return shots
    for name in sorted(os.listdir(shots_dir)):
        if not name.lower().endswith(".png"):
            continue
        key = shot_id(name)
        if not re.search(r"[a-z0-9]", key):
            fail(f"screenshot {name!r} has no letter or digit a screenshot id can be built from: rename it")
        if WINDOWS_DEVICE_RE.fullmatch(key):
            fail(f"screenshot {name!r} reduces to the Windows device name {key!r}: rename it")
        check_shot_file(name, os.path.join(shots_dir, name))
        if key in RESERVED_SHOT_IDS:
            fail(f"screenshot id {key!r} is reserved (the generated index.php files use that name): rename {name!r}")
        if key in shots:
            fail(f"two screenshots reduce to the same id {key!r}: rename one of them")
        shots[key] = os.path.join(shots_dir, name)
    return shots


def sanitise(node, shots, used_shots, section_ids):
    """Keep the contract's tags and attributes; point screenshot links and images at the shot endpoint."""
    for child in list(node.children):
        if not isinstance(child, Tag):
            if type(child) is not NavigableString:
                child.extract()  # Comments, doctypes and processing instructions.
            elif CONTROL_RE.search(child):
                child.replace_with(CONTROL_RE.sub("", child))
            continue
        if child.name in DROPPED_TAGS:
            child.decompose()
            continue
        sanitise(child, shots, used_shots, section_ids)
        if child.name not in ALLOWED_TAGS:
            warn(f"unwrapped <{child.name}>")
            child.unwrap()
            continue
        for attr in list(child.attrs):
            if attr not in ALLOWED_ATTRIBUTES or (attr == "open" and child.name != "details"):
                del child[attr]
                continue
            value = child[attr]
            if isinstance(value, list):
                child[attr] = [CONTROL_RE.sub("", item) for item in value]
            elif isinstance(value, str):
                child[attr] = CONTROL_RE.sub("", value)
        if child.name == "input" and child.get("type") != "checkbox":
            child.decompose()
            continue
        if child.name == "img":
            src = child.get("src", "").strip()
            key = shot_id(src)
            if not src.startswith(SHOT_PREFIX) or key not in shots:
                warn(f"dropped an image that is not in shots/: {src or '(no src)'}")
                child.decompose()
                continue
            used_shots.add(key)
            child["src"] = SHOT_TOKEN.format(key)
            child.attrs.setdefault("loading", "lazy")
        if child.name == "a":
            href = child.get("href", "").strip()
            key = shot_id(href)
            scheme = SCHEME_RE.match(href)
            if href.startswith(SHOT_PREFIX) and key in shots:
                used_shots.add(key)
                child["href"] = SHOT_TOKEN.format(key)
                child["target"] = "_blank"
                child["rel"] = "noopener"
            elif href.startswith("#"):
                child["href"] = href
                if href[1:] not in section_ids and href[1:]:
                    warn(f"link to #{href[1:]}, which is not a section id; kept as is")
            elif scheme:
                child["href"] = scheme.group(0).lower() + href[scheme.end():]
                if scheme.group(1).lower() in ("http", "https"):
                    child["target"] = "_blank"
                    child["rel"] = "noopener noreferrer"
            else:
                warn(f"unwrapped a link with an unsupported href: {href or '(none)'}")
                child.unwrap()


WARNING_CLASSES = {"warn", "warning", "caution"}


def add_class(element, *names):
    classes = list(element.get("class", []))
    element["class"] = classes + [name for name in names if name not in classes]


def add_core_classes(node):
    """Give notes, tables and checklists the admin's own classes (notices stay inline so core does not move them)."""
    for element in [node] + node.find_all(True):
        classes = set(element.get("class", []))
        if element.name == "div" and "note" in classes:
            add_class(element, "notice", "notice-warning" if classes & WARNING_CLASSES else "notice-info", "inline")
        elif element.name == "table":
            add_class(element, "widefat", "striped")
        elif element.name == "div" and "check" in classes:
            add_class(element, "card")


def prefix_ids(node, slug):
    """Prefix every id under node, and node's own, with the slug so ids cannot collide with wp-admin's."""
    for element in [node] + node.find_all(True):
        if element.get("id"):
            element["id"] = f"{slug}-{element['id']}"


def prefix_links(node, slug):
    """Point internal #links at the prefixed ids."""
    for link in node.find_all("a", href=True):
        href = link["href"]
        if href.startswith("#") and len(href) > 1:
            link["href"] = f"#{slug}-{href[1:]}"


def shot_echo(namespace, key):
    """The one PHP tag the generator writes inside the guide markup."""
    return f"<?php echo esc_url( \\{namespace}\\Guide::shot_url( '{key}' ) ); ?>"


def render_view(cover, toc, sections, lang, namespace, slug):
    parts = [f'<div class="{slug}-guide__content" lang="{html.escape(lang, quote=True)}">']
    if cover is not None:
        parts.append(str(cover))
        parts.append('<hr class="wp-header-end">')
    parts.append(f'<div class="{slug}-guide__shell">')
    if toc is not None:
        parts.append(str(toc))
    parts.append("<main>")
    parts.extend(str(section) for section in sections)
    parts.append("</main>")
    parts.append("</div>")
    parts.append("</div>")
    markup = "\n".join(parts)
    # Indentation after a newline carries no meaning outside <pre>; drop it so the file is tab-clean. A <pre> line's first
    # leading space becomes &#32; so the file holds no space-indented line and the text renders unchanged.
    pieces = PRE_RE.split(markup)
    markup = "".join(
        re.sub(r"^ ", "&#32;", piece, flags=re.M) if index % 2 else re.sub(r"(?<=\n)[ \t]+", "", piece)
        for index, piece in enumerate(pieces)
    )
    markup = SHOT_TOKEN_RE.sub(lambda m: shot_echo(namespace, m.group(1)), markup)
    header = (
        "<?php\n"
        "/**\n"
        " * The guide, printed on the guide's admin page.\n"
        " *\n"
        f" * {GENERATED_MARK}. Regenerate the plugin to change this file.\n"
        " *\n"
        f" * @package {namespace}\n"
        " */\n\n"
        "defined( 'ABSPATH' ) || exit;\n"
        "?>\n"
    )
    return header + markup + "\n"


def render_shot(namespace, key, path):
    with open(path, "rb") as handle:
        data = base64.b64encode(handle.read()).decode("ascii")
    return (
        "<?php\n"
        "/**\n"
        f" * Screenshot \"{key}\" of the guide, read by Guide::serve_shot().\n"
        " *\n"
        f" * @package {namespace}\n"
        " */\n\n"
        "defined( 'ABSPATH' ) || exit;\n\n"
        f"return '{data}';\n"
    )


def render_data(namespace, sections, shots, links):
    data = {"sections": sections, "shots": shots, "links": links}
    return (
        "<?php\n"
        "/**\n"
        " * Guide data: section index, screenshot list and the admin screens linked to each section.\n"
        " *\n"
        f" * {GENERATED_MARK}. Regenerate the plugin to change this file.\n"
        " *\n"
        f" * @package {namespace}\n"
        " */\n\n"
        "defined( 'ABSPATH' ) || exit;\n\n"
        f"return {php_array(data)};\n"
    )


